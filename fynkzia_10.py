# Задание 10 (Напишите функцию profile, которая принимает имя, возраст (по умолчанию 18) и любые дополнительные сведения в виде именованных аргументов. Функция возвращает список строк: имя, возраст и каждая дополнительная пара «ключ — значение».)
def profile(name, age=18, **dop):
    info = [f"Имя: {name}", f"Возраст: {age}"]
    for key, value in dop.items():
        info.append(f"{key} — {value}")
    return info

print(profile("Анна"))
print(profile("Олег", 25, city="Москва", job="Програмист"))
