# Задание 6 (Напишите функцию introduce(name, city), у которой город по умолчанию равен «Москва». Функция возвращает строку вида «Меня зовут Анна, я из Москвы». Вызовите её с указанием города и без него.)
def introduce(name, city="Москва"):
    return f"Меня зовут {name}, я из {city}"

print(introduce("Анна"))
print(introduce("Олег", "Тулы"))

