# Задание 9 (Напишите функцию order, которая принимает название товара, количество (по умолчанию 1) и любое число дополнительных позиций. Функция возвращает строку с названием, количеством и списком дополнений, если они есть.)
def order(naz, kol=1, *dop):
    result = f"Товар: {naz}, количество: {kol}"
    if dop:
        result += f", дополнения: {dop}"
    return result

print(order("Мороженое"))
print(order("Мороженое", 2, "Салфетка", "Ложка"))
